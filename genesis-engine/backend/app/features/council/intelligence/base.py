"""
CIVORA — Council Intelligence Base Advisor Interface
Defines the standard contract implemented by all six domain advisor engines.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any, Set
from datetime import datetime, timezone

from app.features.council.intelligence.context import CivilisationContext
from app.features.council.intelligence.evidence import Finding
from app.features.council.intelligence.risk_engine import Risk
from app.features.council.intelligence.recommendation_engine import IntelligenceRecommendation
from app.features.council.intelligence.confidence import calculate_domain_confidence


@dataclass
class AdvisorAnalysisResult:
    """Standardized analytical report generated by an advisor."""
    advisor_id: str
    advisor_name: str
    advisor_title: str
    domain: str
    world_id: str
    simulation_tick: int
    generated_at: str
    overall_status: str  # Optimal, Stable, Attention Required, Critical
    status_summary: str
    findings: List[Finding] = field(default_factory=list)
    risks: List[Risk] = field(default_factory=list)
    recommendations: List[IntelligenceRecommendation] = field(default_factory=list)
    briefing: Dict[str, Any] = field(default_factory=dict)
    confidence: float = 0.85
    data_completeness: float = 0.90
    missing_metrics: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "advisor_id": self.advisor_id,
            "advisorId": self.advisor_id,
            "advisor_name": self.advisor_name,
            "advisorName": self.advisor_name,
            "advisor_title": self.advisor_title,
            "advisorTitle": self.advisor_title,
            "domain": self.domain,
            "world_id": self.world_id,
            "worldId": self.world_id,
            "simulation_tick": self.simulation_tick,
            "generated_at": self.generated_at,
            "overall_status": self.overall_status,
            "status": self.overall_status,
            "status_summary": self.status_summary,
            "statusSummary": self.status_summary,
            "findings": [f.to_dict() for f in self.findings],
            "risks": [r.to_dict() for r in self.risks],
            "recommendations": [rec.to_dict() for rec in self.recommendations],
            "briefing": self.briefing,
            "confidence": self.confidence,
            "confidenceScore": int(self.confidence * 100),
            "data_completeness": self.data_completeness,
            "missing_metrics": self.missing_metrics,
        }


class BaseAdvisor(ABC):
    """Abstract base class for Council Advisor intelligence engines."""

    advisor_id: str
    advisor_name: str
    advisor_title: str
    domain: str
    required_indicators: Set[str] = set()

    @abstractmethod
    def evaluate_findings(self, context: CivilisationContext) -> List[Finding]:
        """Examines authoritative simulation state and produces evidence-backed findings."""
        pass

    @abstractmethod
    def identify_risks(self, context: CivilisationContext, findings: List[Finding]) -> List[Risk]:
        """Synthesizes findings into prospective systemic vulnerabilities and risks."""
        pass

    @abstractmethod
    def generate_recommendations(
        self,
        context: CivilisationContext,
        findings: List[Finding],
        risks: List[Risk]
    ) -> List[IntelligenceRecommendation]:
        """Proposes traceable policy and infrastructural directives grounded in findings."""
        pass

    @abstractmethod
    def compose_formal_speech(
        self,
        context: CivilisationContext,
        findings: List[Finding],
        risks: List[Risk],
        recommendations: List[IntelligenceRecommendation]
    ) -> str:
        """Composes concise, dignified, domain-specific formal counsel for the sovereign."""
        pass

    def calculate_confidence(self, context: CivilisationContext) -> float:
        """Computes mathematically defensible confidence for this advisor's domain."""
        return calculate_domain_confidence(context, self.required_indicators)

    def analyse(self, context: CivilisationContext) -> AdvisorAnalysisResult:
        """Full pipeline execution for this advisor."""
        now = datetime.now(timezone.utc).isoformat()
        confidence = self.calculate_confidence(context)

        # Missing indicators
        missing = [m for m in self.required_indicators if m in context.missing_indicators]
        completeness = round((len(self.required_indicators) - len(missing)) / max(len(self.required_indicators), 1), 2)

        # 1. Findings
        findings = self.evaluate_findings(context)

        # 2. Risks
        risks = self.identify_risks(context, findings)

        # 3. Recommendations
        recommendations = self.generate_recommendations(context, findings, risks)

        # Determine overall status
        severities = [f.severity for f in findings] + [r.severity for r in risks]
        if "critical" in severities or "Critical" in severities:
            status = "Critical"
        elif "high" in severities or "High" in severities:
            status = "Attention Required"
        elif "moderate" in severities or "Moderate" in severities:
            status = "Stable"
        else:
            status = "Optimal"

        # Summary
        if status == "Critical":
            summary = f"Urgent departmental crisis detected in {self.domain}."
        elif status == "Attention Required":
            summary = f"Vulnerabilities emerging in {self.domain} requiring sovereign review."
        elif status == "Stable":
            summary = f"Operational equilibrium maintained in {self.domain}."
        else:
            summary = f"Optimal conditions achieved across {self.domain}."

        # Formal speech
        formal_speech = self.compose_formal_speech(context, findings, risks, recommendations)

        # Key metrics for briefing
        briefing_data = {
            "advisorId": self.advisor_id,
            "date": f"Year {context.year} · Day {context.day}",
            "headline": f"{self.advisor_title} — State of {self.domain}",
            "formalSpeech": formal_speech,
            "supportingObservations": [
                {
                    "id": f.id,
                    "title": f.title,
                    "detail": f.description,
                    "severity": "urgent" if f.severity in ["high", "critical"] else "warning" if f.severity == "moderate" else "info",
                    "recordedDate": f"Tick {context.tick}",
                }
                for f in findings[:4]
            ],
            "proposedDirectives": [r.title for r in recommendations],
            "systemicConsequences": [
                f"Implementing '{r.title}' expected to yield: {', '.join(r.expected_benefits[:2])}"
                for r in recommendations[:2]
            ],
            "keyMetrics": [
                {
                    "id": f"metric-{idx}",
                    "label": ev.metric_name.replace("_", " ").title(),
                    "value": ev.observed_value,
                    "trend": ev.trend if ev.trend in ["up", "down", "neutral"] else "neutral",
                    "status": "warning" if f.severity in ["high", "critical"] else "stable",
                    "description": ev.interpretation,
                }
                for idx, f in enumerate(findings[:3])
                for ev in f.supporting_evidence[:1]
            ],
            "confidenceScore": int(confidence * 100),
        }

        return AdvisorAnalysisResult(
            advisor_id=self.advisor_id,
            advisor_name=self.advisor_name,
            advisor_title=self.advisor_title,
            domain=self.domain,
            world_id=context.world_id,
            simulation_tick=context.tick,
            generated_at=now,
            overall_status=status,
            status_summary=summary,
            findings=findings,
            risks=risks,
            recommendations=recommendations,
            briefing=briefing_data,
            confidence=confidence,
            data_completeness=completeness,
            missing_metrics=missing,
        )
