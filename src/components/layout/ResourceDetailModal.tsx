import React from 'react';
import {
  X,
  TrendingUp,
  TrendingDown,
  AlertTriangle,
  Wheat,
  Droplets,
  Zap,
  Package,
  FlaskConical,
  Coins,
  Users,
  ShieldCheck,
  Building2,
  ArrowRight,
} from 'lucide-react';
import { useGameState } from '../../context/GameStateContext';
import { ResponsiveContainer, AreaChart, Area, XAxis, YAxis, Tooltip } from 'recharts';

export type SelectedResourceKey =
  | 'population'
  | 'food'
  | 'water'
  | 'energy'
  | 'materials'
  | 'research'
  | 'crc';

interface ResourceDetailModalProps {
  resourceKey: SelectedResourceKey | null;
  onClose: () => void;
  onNavigate?: (page: string) => void;
}

export default function ResourceDetailModal({
  resourceKey,
  onClose,
  onNavigate,
}: ResourceDetailModalProps) {
  const { resources, rates, economyReport, districts, placedBuildings } = useGameState();

  if (!resourceKey) return null;

  const { resources: resFlow, economy } = economyReport;

  const resourceConfigs: Record<
    SelectedResourceKey,
    {
      name: string;
      category: string;
      icon: React.ComponentType<{ size?: number; className?: string }>;
      color: string;
      unit: string;
      stockpile: number;
      produced: number;
      consumed: number;
      net: number;
      description: string;
      producers: string[];
      consumers: string[];
      recommendation: string;
    }
  > = {
    population: {
      name: 'Citizens & Demographic Workforce',
      category: 'Demographics',
      icon: Users,
      color: '#8FA879',
      unit: 'Citizens',
      stockpile: resources.population,
      produced: Math.round(resources.population * (rates.populationGrowthRate / 100)),
      consumed: 0,
      net: Math.round(resources.population * (rates.populationGrowthRate / 100)),
      description: 'The foundation of the empire. Drives industry productivity, research laboratories, and civic stability.',
      producers: ['Residential Arcologies', 'Colonial Habitations'],
      consumers: ['Municipal Facilities', 'Industrial Foundries'],
      recommendation: 'Expand residential zoning and water reserves to sustain steady demographic influx.',
    },
    food: {
      name: 'Agricultural Rations & Biomass',
      category: 'Nutritional Security',
      icon: Wheat,
      color: '#C5A66A',
      unit: 'Rations',
      stockpile: resources.food,
      produced: resFlow.foodProduced,
      consumed: resFlow.foodConsumed,
      net: resFlow.foodNet,
      description: 'Essential sustenance for all citizen cohorts. Shortages rapidly deteriorate public health and social order.',
      producers: ['Bio-Dome Farms', 'Terraced Hydroponics', 'Grain Silos'],
      consumers: ['Citizen Quarters', 'Commercial Taverns'],
      recommendation: resFlow.foodNet < 0 ? 'Urgent: Construct additional Bio-Domes or negotiate agrarian trade import.' : 'Food reserves optimal. Surplus exported or stored in regional silos.',
    },
    water: {
      name: 'Purified Freshwater & Aqueducts',
      category: 'Hydrological Grid',
      icon: Droplets,
      color: '#6e98b3',
      unit: 'kL/day',
      stockpile: resources.water,
      produced: resFlow.waterProduced,
      consumed: resFlow.waterConsumed,
      net: resFlow.waterNet,
      description: 'Clean drinking water and industrial cooling fluid transported through monumental aqueduct canals.',
      producers: ['Aqueduct Networks', 'Water Purification Plants', 'Reservoirs'],
      consumers: ['Hydroponic Domes', 'Nanofab Smelters', 'Hospitals'],
      recommendation: resFlow.waterNet < 0 ? 'Warning: Water deficit detected. Extend river channels or upgrade filtration capacity.' : 'Aqueduct throughput steady with surplus cooling reserves.',
    },
    energy: {
      name: 'Grid Power & Kinetic Generation',
      category: 'Energy Network',
      icon: Zap,
      color: '#D6A75E',
      unit: 'MW',
      stockpile: resources.energy,
      produced: resFlow.energyProducedMW,
      consumed: resFlow.energyConsumedMW,
      net: resFlow.energyNetMW,
      description: 'Continuous clean electricity generated by solar concentrators, vortex wind turbines, and geothermal plants.',
      producers: ['Vortex Wind Turbines', 'Solar Concentrator Arrays', 'Thermal Plants'],
      consumers: ['Industrial Sector', 'Transit Pods', 'Research Observatories'],
      recommendation: resFlow.energyNetMW < 0 ? 'Critical: Brownout risk imminent. Commission wind turbines in northern ridgeline.' : 'Power balance positive. Grid operating at optimal harmonic frequency.',
    },
    materials: {
      name: 'Titanium & Building Materials',
      category: 'Structural Fabrication',
      icon: Package,
      color: '#9F8859',
      unit: 'Tons',
      stockpile: resources.materials,
      produced: resFlow.materialsProduced,
      consumed: resFlow.materialsConsumed,
      net: resFlow.materialsNet,
      description: 'Refined alloys, stone, and composite materials required for erecting and upgrading municipal infrastructure.',
      producers: ['Vulcan Nanofab Smelters', 'Quarries', 'Fabrication Yards'],
      consumers: ['Active Construction Staging', 'Structural Maintenance'],
      recommendation: 'Accumulate at least 1,500 materials before undertaking major arcology expansions.',
    },
    research: {
      name: 'Research Points (RP)',
      category: 'Scientific Output',
      icon: FlaskConical,
      color: '#8FA879',
      unit: 'RP/day',
      stockpile: resources.researchPoints,
      produced: rates.researchRate,
      consumed: 0,
      net: rates.researchRate,
      description: 'Generated by scholars and laboratories to unlock historical breakthrough nodes in the Technology Tree.',
      producers: ['Research Observatory', 'Academy of Sciences', 'Cognitive Labs'],
      consumers: ['Active Technology Tree Breakthroughs'],
      recommendation: 'Assign specialized scientists to the Observatory to accelerate breakthrough velocities.',
    },
    crc: {
      name: 'Civora Research Credits (CRC)',
      category: 'Treasury & Grants',
      icon: Coins,
      color: '#C5A66A',
      unit: 'CRC',
      stockpile: resources.grc,
      produced: Math.max(0, economy.netDailyCashFlow),
      consumed: Math.abs(Math.min(0, economy.netDailyCashFlow)),
      net: economy.netDailyCashFlow,
      description: 'Authoritative research currency awarded through confirmed civilisation milestones, used for premium scenarios and scientific experiments.',
      producers: ['Civilisation Milestones', 'Scientific Discoveries', 'Export Trade'],
      consumers: ['Future Simulator Runs', 'Observatory Scientific Trials'],
      recommendation: 'Complete active empire missions to receive authoritative treasury grants.',
    },
  };

  const config = resourceConfigs[resourceKey];
  const Icon = config.icon;

  // Generate 7-day trend history
  const trendData = [
    { day: 'D-6', val: Math.round(config.stockpile * 0.88) },
    { day: 'D-5', val: Math.round(config.stockpile * 0.91) },
    { day: 'D-4', val: Math.round(config.stockpile * 0.94) },
    { day: 'D-3', val: Math.round(config.stockpile * 0.96) },
    { day: 'D-2', val: Math.round(config.stockpile * 0.98) },
    { day: 'D-1', val: Math.round(config.stockpile * 0.99) },
    { day: 'Live', val: config.stockpile },
  ];

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-xs">
      <div className="w-full max-w-2xl bg-[#171D18] border border-[#2B372C] rounded-lg shadow-2xl overflow-hidden flex flex-col text-[#EAE3D2] animate-in fade-in zoom-in-95 duration-150">
        {/* Header */}
        <div className="px-5 py-4 border-b border-[#2B372C] bg-[#121713] flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div
              className="w-10 h-10 rounded-md border flex items-center justify-center"
              style={{ backgroundColor: `${config.color}15`, borderColor: config.color }}
            >
              <span style={{ color: config.color }}>
                <Icon size={20} />
              </span>
            </div>
            <div>
              <span className="text-[10px] font-mono uppercase tracking-[0.18em] text-[#C5A66A]">
                {config.category}
              </span>
              <h2 className="text-base font-bold font-cinzel text-[#EAE3D2] leading-tight">
                {config.name}
              </h2>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 rounded text-[#A5AD9D] hover:text-[#EAE3D2] hover:bg-[#202820] transition-colors"
          >
            <X size={18} />
          </button>
        </div>

        {/* Content Body */}
        <div className="p-6 space-y-6 overflow-y-auto max-h-[75vh] custom-scrollbar">
          {/* Key Metrics Grid */}
          <div className="grid grid-cols-3 gap-3">
            <div className="p-3.5 rounded bg-[#202820] border border-[#2B372C]">
              <span className="text-[10px] font-mono text-[#A5AD9D] block uppercase">Current Stockpile</span>
              <span className="text-lg font-bold font-mono text-[#EAE3D2]">
                {config.stockpile.toLocaleString()} {config.unit}
              </span>
            </div>

            <div className="p-3.5 rounded bg-[#202820] border border-[#2B372C]">
              <span className="text-[10px] font-mono text-[#A5AD9D] block uppercase">Daily Production</span>
              <span className="text-lg font-bold font-mono text-[#8FA879]">
                +{config.produced.toLocaleString()} {config.unit}
              </span>
            </div>

            <div className="p-3.5 rounded bg-[#202820] border border-[#2B372C]">
              <span className="text-[10px] font-mono text-[#A5AD9D] block uppercase">Net Daily Balance</span>
              <div className="flex items-center gap-1.5">
                {config.net >= 0 ? (
                  <TrendingUp size={16} className="text-[#8FA879]" />
                ) : (
                  <TrendingDown size={16} className="text-[#C87569]" />
                )}
                <span
                  className={`text-lg font-bold font-mono ${
                    config.net >= 0 ? 'text-[#8FA879]' : 'text-[#C87569]'
                  }`}
                >
                  {config.net >= 0 ? `+${config.net.toLocaleString()}` : config.net.toLocaleString()}
                </span>
              </div>
            </div>
          </div>

          {/* Historical Trend Chart */}
          <div className="p-4 rounded bg-[#1C231E] border border-[#2B372C]">
            <div className="flex items-center justify-between mb-3">
              <span className="text-xs font-mono font-bold uppercase tracking-wider text-[#C5A66A]">
                7-Day Stockpile Velocity
              </span>
              <span className="text-[10px] font-mono text-[#A5AD9D]">Authoritative Observation</span>
            </div>
            <div className="h-32 w-full">
              <ResponsiveContainer width="100%" height="100%">
                <AreaChart data={trendData}>
                  <defs>
                    <linearGradient id="resourceGrad" x1="0" y1="0" x2="0" y2="1">
                      <stop offset="5%" stopColor={config.color} stopOpacity={0.35} />
                      <stop offset="95%" stopColor={config.color} stopOpacity={0} />
                    </linearGradient>
                  </defs>
                  <XAxis dataKey="day" stroke="#7A8473" fontSize={10} tickLine={false} />
                  <YAxis stroke="#7A8473" fontSize={10} tickLine={false} domain={['auto', 'auto']} />
                  <Tooltip
                    contentStyle={{ backgroundColor: '#171D18', borderColor: '#2B372C', color: '#EAE3D2', fontSize: '11px' }}
                  />
                  <Area type="monotone" dataKey="val" stroke={config.color} strokeWidth={2} fill="url(#resourceGrad)" />
                </AreaChart>
              </ResponsiveContainer>
            </div>
          </div>

          {/* Producers & Consumers */}
          <div className="grid grid-cols-2 gap-4">
            <div className="p-3.5 rounded bg-[#202820] border border-[#2B372C] space-y-2">
              <span className="text-[10px] font-mono text-[#C5A66A] uppercase font-bold tracking-wider block">
                Primary Sources
              </span>
              <div className="space-y-1">
                {config.producers.map((p) => (
                  <div key={p} className="flex items-center gap-2 text-xs text-[#EAE3D2]">
                    <span className="w-1.5 h-1.5 rounded-full bg-[#8FA879]" />
                    <span>{p}</span>
                  </div>
                ))}
              </div>
            </div>

            <div className="p-3.5 rounded bg-[#202820] border border-[#2B372C] space-y-2">
              <span className="text-[10px] font-mono text-[#D6A75E] uppercase font-bold tracking-wider block">
                Primary Outflows
              </span>
              <div className="space-y-1">
                {config.consumers.map((c) => (
                  <div key={c} className="flex items-center gap-2 text-xs text-[#A5AD9D]">
                    <span className="w-1.5 h-1.5 rounded-full bg-[#9F8859]" />
                    <span>{c}</span>
                  </div>
                ))}
              </div>
            </div>
          </div>

          {/* Strategic Recommendation */}
          <div className="p-3.5 rounded bg-[#1C231E] border border-[#3D4F3F] flex items-start gap-3">
            <ShieldCheck size={18} className="text-[#C5A66A] shrink-0 mt-0.5" />
            <div className="text-xs text-[#EAE3D2] leading-relaxed">
              <span className="font-bold text-[#C5A66A] block mb-0.5 font-cinzel">Civilisation Directive</span>
              {config.recommendation}
            </div>
          </div>
        </div>

        {/* Footer */}
        <div className="px-5 py-3 border-t border-[#2B372C] bg-[#121713] flex items-center justify-between">
          <span className="text-[10px] font-mono text-[#7A8473]">
            Telemetry synchronised with Civora Engine
          </span>
          <div className="flex gap-2">
            {onNavigate && (
              <button
                onClick={() => {
                  onClose();
                  onNavigate('Economy & Resources');
                }}
                className="px-3 py-1.5 rounded text-xs font-medium text-[#C5A66A] hover:text-[#FFFFFF] hover:bg-[#202820] border border-[#C5A66A]/30 flex items-center gap-1.5 transition-colors"
              >
                <span>Macro Ledger</span>
                <ArrowRight size={13} />
              </button>
            )}
            <button
              onClick={onClose}
              className="px-4 py-1.5 rounded text-xs font-semibold bg-[#202820] hover:bg-[#283228] text-[#EAE3D2] border border-[#2B372C] transition-colors"
            >
              Dismiss
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
