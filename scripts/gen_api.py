#!/usr/bin/env python3
import json
import os
import re

def python_type_to_ts(prop):
    if '$ref' in prop:
        ref_name = prop['$ref'].split('/')[-1]
        return ref_name
    p_type = prop.get('type')
    if p_type == 'integer' or p_type == 'number':
        return 'number'
    elif p_type == 'string':
        if 'enum' in prop:
            return ' | '.join(f"'{v}'" for v in prop['enum'])
        return 'string'
    elif p_type == 'boolean':
        return 'boolean'
    elif p_type == 'array':
        items = prop.get('items', {})
        return f"{python_type_to_ts(items)}[]"
    elif p_type == 'object':
        additional = prop.get('additionalProperties')
        if additional:
            val_type = python_type_to_ts(additional) if isinstance(additional, dict) else 'any'
            return f"Record<string, {val_type}>"
        return 'Record<string, any>'
    elif 'anyOf' in prop:
        sub_types = [python_type_to_ts(sub) for sub in prop['anyOf'] if sub.get('type') != 'null']
        if any(sub.get('type') == 'null' for sub in prop['anyOf']):
            return f"({' | '.join(sub_types)}) | null"
        return ' | '.join(sub_types) or 'any'
    return 'any'

def main():
    contract_path = 'docs/contract/backend_contract.json'
    if not os.path.exists(contract_path):
        print("Contract not found!")
        return

    with open(contract_path, 'r') as f:
        contract = json.load(f)

    openapi = contract.get('openapi', {})
    schemas = openapi.get('components', {}).get('schemas', {})

    out_dir = 'src/api/generated'
    os.makedirs(out_dir, exist_ok=True)

    # 1. Generate types.ts
    types_content = [
        "/**",
        " * Auto-generated TypeScript definitions from Backend OpenAPI Schema.",
        " * DO NOT EDIT MANUALLY - Generated by scripts/gen_api.py",
        " */",
        ""
    ]

    for schema_name, schema_def in sorted(schemas.items()):
        description = schema_def.get('description', '')
        if description:
            types_content.append(f"/** {description} */")
        
        properties = schema_def.get('properties', {})
        required = set(schema_def.get('required', []))
        
        types_content.append(f"export interface {schema_name} {{")
        for prop_name, prop_def in properties.items():
            is_req = prop_name in required
            ts_type = python_type_to_ts(prop_def)
            q_mark = "" if is_req else "?"
            doc = prop_def.get('description', '')
            if doc:
                types_content.append(f"  /** {doc} */")
            types_content.append(f"  {prop_name}{q_mark}: {ts_type};")
        types_content.append("}")
        types_content.append("")

    with open(os.path.join(out_dir, 'types.ts'), 'w') as f:
        f.write('\n'.join(types_content))
    print(f"Generated {len(schemas)} schemas into src/api/generated/types.ts")

    # 2. Generate validator.ts
    validator_content = [
        "/**",
        " * Runtime boundary validator for API responses.",
        " * Catches type mismatches, missing required fields, and emits UI alert banners.",
        " */",
        "",
        "export interface BoundaryValidationError {",
        "  endpoint: string;",
        "  field: string;",
        "  expected: string;",
        "  actual: any;",
        "  timestamp: number;",
        "}",
        "",
        "type ValidationListener = (error: BoundaryValidationError) => void;",
        "const listeners: Set<ValidationListener> = new Set();",
        "",
        "export function onValidationError(listener: ValidationListener): () => void {",
        "  listeners.add(listener);",
        "  return () => listeners.delete(listener);",
        "}",
        "",
        "export function notifyValidationError(err: BoundaryValidationError): void {",
        "  console.error(`[API Boundary Validation Error] at ${err.endpoint}: Field '${err.field}' expected ${err.expected}, got:`, err.actual);",
        "  listeners.forEach((l) => l(err));",
        "}",
        "",
        "export function validateObject<T extends object>(",
        "  data: any,",
        "  requiredFields: (keyof T)[],",
        "  endpoint: string,",
        "  expectedTypes?: Partial<Record<keyof T, 'string' | 'number' | 'boolean' | 'object' | 'array'>>",
        "): T {",
        "  if (!data || typeof data !== 'object') {",
        "    notifyValidationError({",
        "      endpoint,",
        "      field: 'ROOT',",
        "      expected: 'object',",
        "      actual: typeof data,",
        "      timestamp: Date.now(),",
        "    });",
        "    return data as T;",
        "  }",
        "",
        "  for (const field of requiredFields) {",
        "    if (data[field] === undefined || data[field] === null) {",
        "      notifyValidationError({",
        "        endpoint,",
        "        field: String(field),",
        "        expected: 'defined',",
        "        actual: data[field],",
        "        timestamp: Date.now(),",
        "      });",
        "    } else if (expectedTypes && expectedTypes[field]) {",
        "      const exp = expectedTypes[field]!;",
        "      const act = Array.isArray(data[field]) ? 'array' : typeof data[field];",
        "      if (exp !== act) {",
        "        notifyValidationError({",
        "          endpoint,",
        "          field: String(field),",
        "          expected: exp,",
        "          actual: act,",
        "          timestamp: Date.now(),",
        "        });",
        "      }",
        "    }",
        "  }",
        "",
        "  return data as T;",
        "}",
        ""
    ]

    with open(os.path.join(out_dir, 'validator.ts'), 'w') as f:
        f.write('\n'.join(validator_content))
    print("Generated src/api/generated/validator.ts")

    # 3. Generate client.ts
    client_content = [
        "/**",
        " * Generated Typed API Client with Boundary Validation.",
        " * Interacts with backend OpenAPI routes cleanly and transparently.",
        " */",
        "import axios, { AxiosInstance } from 'axios';",
        "import * as Types from './types';",
        "import { validateObject } from './validator';",
        "",
        "export function createGeneratedApiClient(customAxios?: AxiosInstance) {",
        "  const client = customAxios || axios.create({ baseURL: '/api/v1', timeout: 10000 });",
        "",
        "  return {",
        "    // Health and vitals",
        "    async getHealth() {",
        "      const res = await client.get('/health');",
        "      return res.data;",
        "    },",
        "    async getMLHealth() {",
        "      const res = await client.get('/ml/health');",
        "      return res.data;",
        "    },",
        "",
        "    // Worlds & Simulation",
        "    async listWorlds(): Promise<Types.WorldSummary[]> {",
        "      const res = await client.get('/worlds');",
        "      return res.data;",
        "    },",
        "    async getWorld(worldId: string): Promise<any> {",
        "      const res = await client.get(`/worlds/${encodeURIComponent(worldId)}`);",
        "      return validateObject(res.data, ['id', 'name'], `/worlds/${worldId}`);",
        "    },",
        "    async advanceSimulation(worldId: string, ticks: number = 1) {",
        "      const res = await client.post(`/worlds/${encodeURIComponent(worldId)}/simulation/advance`, { ticks });",
        "      return res.data;",
        "    },",
        "",
        "    // Budget & Bonds",
        "    async getBudget(worldId: string) {",
        "      const res = await client.get(`/worlds/${encodeURIComponent(worldId)}/budget`);",
        "      return validateObject(res.data, ['rates', 'sector_budgets'], `/worlds/${worldId}/budget`);",
        "    },",
        "    async updateBudget(worldId: string, data: Types.BudgetUpdateRequest) {",
        "      const res = await client.post(`/worlds/${encodeURIComponent(worldId)}/budget`, data);",
        "      return res.data;",
        "    },",
        "    async issueBond(worldId: string, amount: number) {",
        "      const res = await client.post(`/worlds/${encodeURIComponent(worldId)}/bonds/issue`, { amount });",
        "      return res.data;",
        "    },",
        "    async repayBond(worldId: string, amount: number) {",
        "      const res = await client.post(`/worlds/${encodeURIComponent(worldId)}/bonds/repay`, { amount });",
        "      return res.data;",
        "    },",
        "",
        "    // Buildings & Infrastructure",
        "    async getBuildings(worldId: string): Promise<Types.Building[]> {",
        "      const res = await client.get(`/worlds/${encodeURIComponent(worldId)}/buildings`);",
        "      return res.data;",
        "    },",
        "    async constructBuilding(worldId: string, req: Types.BuildingConstructRequest): Promise<Types.Building> {",
        "      const res = await client.post(`/worlds/${encodeURIComponent(worldId)}/buildings`, req);",
        "      return validateObject<Types.Building>(res.data, ['id', 'type'], `/worlds/${worldId}/buildings`);",
        "    },",
        "    async decommissionBuilding(worldId: string, buildingId: string) {",
        "      const res = await client.delete(`/worlds/${encodeURIComponent(worldId)}/buildings/${encodeURIComponent(buildingId)}`);",
        "      return res.data;",
        "    },",
        "",
        "    // Technology",
        "    async getTechnologyOverview(worldId: string): Promise<Types.TechnologyOverviewResponse> {",
        "      const res = await client.get(`/worlds/${encodeURIComponent(worldId)}/technology/overview`);",
        "      return validateObject<Types.TechnologyOverviewResponse>(res.data, ['world_id'], `/worlds/${worldId}/technology/overview`);",
        "    },",
        "    async unlockTechnology(worldId: string, techId: string) {",
        "      const res = await client.post(`/worlds/${encodeURIComponent(worldId)}/technologies/${encodeURIComponent(techId)}/unlock`);",
        "      return res.data;",
        "    },",
        "",
        "    // Policies",
        "    async getPolicies(worldId: string): Promise<Types.Policy[]> {",
        "      const res = await client.get(`/worlds/${encodeURIComponent(worldId)}/policies`);",
        "      return res.data;",
        "    },",
        "    async updatePolicy(worldId: string, policyId: string, req: Types.PolicyUpdateRequest) {",
        "      const res = await client.post(`/worlds/${encodeURIComponent(worldId)}/policies/${encodeURIComponent(policyId)}/toggle`, req);",
        "      return res.data;",
        "    },",
        "  };",
        "}",
        ""
    ]

    with open(os.path.join(out_dir, 'client.ts'), 'w') as f:
        f.write('\n'.join(client_content))
    print("Generated src/api/generated/client.ts")

    # 4. Generate index.ts
    index_content = [
        "export * from './types';",
        "export type { BoundaryValidationError } from './validator';",
        "export { onValidationError, notifyValidationError, validateObject } from './validator';",
        "export * from './client';",
        ""
    ]
    with open(os.path.join(out_dir, 'index.ts'), 'w') as f:
        f.write('\n'.join(index_content))
    print("Generated src/api/generated/index.ts")

if __name__ == '__main__':
    main()
